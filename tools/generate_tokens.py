#!/usr/bin/env python3
"""Generate checked-in Android token constants from design-system/tokens.json.

The source of truth is design-system/tokens.json. Do not hand-edit generated
output. Run with --check in CI to detect drift.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design-system" / "tokens.json"
OUTPUT = (
    ROOT
    / "app/src/main/java/io/github/baitian6641/cloudydata/design/CloudyTokens.kt"
)


def color_long(value: str) -> int:
    if not (value.startswith("#") and len(value) == 7):
        raise ValueError(f"unsupported color {value!r}")
    return int(value[1:], 16) | 0xFF000000


def render(data: dict) -> str:
    colors = data["color"]
    typography = data["typography"]
    density = data["density"]
    shape = data["shape"]
    motion = data["motion"]
    geometry = data["geometry"]
    chart = data["chart"]

    lines: list[str] = []
    add = lines.append
    add("// Generated by tools/generate_tokens.py from design-system/tokens.json.")
    add("// Provisional Cloudy token source; see docs/decisions/0002-provisional-design-tokens.md.")
    add("package io.github.baitian6641.cloudydata.design")
    add("")
    add("object CloudyTokens {")
    add("    const val SCHEMA_VERSION = 1")
    add("")

    for theme in ("light", "dark"):
        add(f"    object {theme.capitalize()} {{")
        for key, value in colors[theme].items():
            add(f"        const val {key} = 0x{color_long(value):08X}L")
        add("    }")
        add("")

    add("    object Type {")
    for key, value in typography.items():
        add(f"        const val {key}SizeSp = {value['sizeSp']}f")
        add(f"        const val {key}LineHeightSp = {value['lineHeightSp']}f")
        add(f"        const val {key}Weight = {value['weight']}")
    add("    }")
    add("")

    add("    object Density {")
    for key, value in density.items():
        name = "".join(part.capitalize() for part in key.split("_"))
        name = key[0].upper() + key[1:]
        add(f"        object {name} {{")
        add(f"            const val minTargetDp = {value['minTargetDp']}f")
        add(f"            const val spaceSmallDp = {value['spaceSmallDp']}f")
        add(f"            const val spaceMediumDp = {value['spaceMediumDp']}f")
        add(f"            const val spaceLargeDp = {value['spaceLargeDp']}f")
        add("        }")
    add("    }")
    add("")

    add("    object Shape {")
    for key, value in shape.items():
        add(f"        const val {key} = {value}f")
    add("    }")
    add("")

    add("    object Motion {")
    for key, value in motion.items():
        add(f"        const val {key} = {value}")
    add("    }")
    add("")

    add("    object Geometry {")
    for key, value in geometry.items():
        add(f"        const val {key} = {value}f")
    add("    }")
    add("")

    add("    object Chart {")
    for theme in ("light", "dark"):
        palette = ", ".join(hex(color_long(v)) for v in chart["categorical"][theme])
        add(f"        val categorical{theme.capitalize()} = longArrayOf({palette})")
    for theme in ("light", "dark"):
        palette = ", ".join(hex(color_long(v)) for v in chart["sequential"][theme])
        add(f"        val sequential{theme.capitalize()} = longArrayOf({palette})")
    for theme in ("light", "dark"):
        palette = ", ".join(hex(color_long(v)) for v in chart["diverging"][theme])
        add(f"        val diverging{theme.capitalize()} = longArrayOf({palette})")
    add(f"        const val missingLight = 0x{color_long(chart['missing']['light']):08X}L")
    add(f"        const val missingDark = 0x{color_long(chart['missing']['dark']):08X}L")
    add("    }")
    add("}")
    add("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text())
    rendered = render(data)
    if args.check:
        actual = OUTPUT.read_text() if OUTPUT.exists() else ""
        if actual != rendered:
            print(f"drift: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("token output current")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(rendered)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
